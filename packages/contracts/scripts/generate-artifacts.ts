/**
 * Artifacts derived from the route registry: the OpenAPI document and the runtime
 * route manifest for browser clients. `--check` fails when either is stale.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { apiRoutes, buildOpenApiDocument } from '../src/index.js';

const openApiPath = fileURLToPath(new URL('../openapi/openapi.json', import.meta.url));
const manifestPath = fileURLToPath(new URL('../src/generated/route-manifest.ts', import.meta.url));

function literal(value: string | number | boolean): string {
  return typeof value === 'string' ? `'${value.replaceAll("'", "\\'")}'` : String(value);
}

function manifestSource(): string {
  const entries = Object.entries(apiRoutes).map(([name, route]) => {
    const meta = {
      method: route.method,
      path: route.path,
      status: route.status,
      auth: route.auth,
      hasResponseBody: route.response !== null,
    };
    const fields = Object.entries(meta).map(([key, value]) => `${key}: ${literal(value)}`);
    return `  ${name}: { ${fields.join(', ')} },`;
  });
  return [
    '// @generated by packages/contracts/scripts/generate-artifacts.ts from the route registry.',
    '// Do not edit: run `pnpm contracts:generate`.',
    "import type { RouteMeta } from '../route-meta.js';",
    "import type { ApiRoutes } from '../routes/index.js';",
    '',
    'export const routeManifest = {',
    ...entries,
    '} as const satisfies Record<keyof ApiRoutes, RouteMeta>;',
    '',
  ].join('\n');
}

const artifacts = [
  { path: openApiPath, content: `${JSON.stringify(buildOpenApiDocument(apiRoutes), null, 2)}\n` },
  { path: manifestPath, content: manifestSource() },
];

if (process.argv.includes('--check')) {
  const stale: string[] = [];
  for (const artifact of artifacts) {
    if ((await readFile(artifact.path, 'utf8').catch(() => '')) !== artifact.content) {
      stale.push(artifact.path);
    }
  }
  if (stale.length > 0) {
    console.error(
      `Outdated contract artifacts (run \`pnpm contracts:generate\`):\n${stale.join('\n')}`,
    );
    process.exit(1);
  }
  console.log('Contract artifacts are up to date.');
} else {
  for (const artifact of artifacts) {
    await writeFile(artifact.path, artifact.content);
    console.log(`Wrote ${artifact.path}`);
  }
}
